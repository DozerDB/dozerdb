package org.neo4j.cypher.internal

import org.neo4j.cypher.internal.expressions.AutoExtractedParameter
import org.neo4j.cypher.internal.expressions.ExplicitParameter
import org.neo4j.cypher.internal.expressions.SensitiveAutoParameter
import org.neo4j.cypher.internal.expressions.SensitiveParameter
import org.neo4j.cypher.internal.logical.plans.LogicalPlan
import org.neo4j.cypher.internal.runtime.ExecutionMode
import org.neo4j.cypher.internal.runtime.InputDataStream
import org.neo4j.cypher.internal.runtime.QueryContext
import org.neo4j.cypher.internal.util.Rewriter
import org.neo4j.cypher.internal.util.bottomUp
import org.neo4j.cypher.result.RuntimeResult
import org.neo4j.kernel.impl.query.QuerySubscriber
import org.neo4j.values.AnyValue
import org.neo4j.values.virtual.MapValue
import org.neo4j.values.virtual.MapValueBuilder

/** Keeps client parameter names out of the identifiers generated by administration planners. */
private[internal] object DozerDbAdministrationParameters {
  private val prefix = "dozerdbParameter_"

  private def key(name: String): String = {
    if (name.matches("[A-Za-z][A-Za-z0-9_]*") && !name.startsWith(prefix)) name
    else prefix + name.iterator.map(character => f"${character.toInt}%04x").mkString
  }

  def compile(plan: LogicalPlan)(compilePlan: LogicalPlan => ExecutionPlan): ExecutionPlan = {
    // Rewrite the plan and its input map together. Reserving the output prefix makes
    // the mapping injective, including when a client supplies a generated-looking key.
    // Sensitive markers remain attached; parameter values are never copied or rendered.
    val renamed = plan.endoRewrite(bottomUp(Rewriter.lift {
      case parameter: ExplicitParameter if key(parameter.name) != parameter.name =>
        if (parameter.isInstanceOf[SensitiveAutoParameter]) {
          new ExplicitParameter(key(parameter.name), parameter.parameterType, parameter.sizeHint)(parameter.position)
            with SensitiveAutoParameter
        } else if (parameter.isInstanceOf[SensitiveParameter]) {
          new ExplicitParameter(key(parameter.name), parameter.parameterType, parameter.sizeHint)(parameter.position)
            with SensitiveParameter
        } else parameter.copy(name = key(parameter.name))(parameter.position)
      case parameter: AutoExtractedParameter if key(parameter.name) != parameter.name =>
        if (parameter.isInstanceOf[SensitiveAutoParameter]) {
          new AutoExtractedParameter(
            key(parameter.name),
            parameter.parameterType,
            parameter.sizeHint
          )(parameter.position)
            with SensitiveAutoParameter
        } else if (parameter.isInstanceOf[SensitiveParameter]) {
          new AutoExtractedParameter(
            key(parameter.name),
            parameter.parameterType,
            parameter.sizeHint
          )(parameter.position)
            with SensitiveParameter
        } else parameter.copy(name = key(parameter.name))(parameter.position)
    }))
    val compiled = compilePlan(renamed)
    new DelegatingExecutionPlan(compiled) {
      override def threadSafeExecutionResources(): Option[ResourceManagerFactory] =
        compiled.threadSafeExecutionResources()
      override def operatorMetadata = compiled.operatorMetadata
      override def rewrittenPlan = compiled.rewrittenPlan
      override def maybeBatchSize = compiled.maybeBatchSize
      override def internalPlanDescriptionRewriter = compiled.internalPlanDescriptionRewriter
      override def generatedByteCodeSize: Long = compiled.generatedByteCodeSize

      override def run(
        queryContext: QueryContext,
        executionMode: ExecutionMode,
        params: MapValue,
        prePopulateResults: Boolean,
        input: InputDataStream,
        subscriber: QuerySubscriber
      ): RuntimeResult = {
        val inputs = new MapValueBuilder(params.size())
        params.foreach((name: String, value: AnyValue) => {
          inputs.add(key(name), value)
          ()
        })
        compiled.run(queryContext, executionMode, inputs.build(), prePopulateResults, input, subscriber)
      }
    }
  }
}
